"""Read-only Proxmox VE API client using the Python standard library."""
import json
import os
import ssl
from pathlib import Path
from urllib.request import Request, urlopen


from rvpi_automation.inventory import normalize_vm_inventory

def load_token_secret():
    """Load the Proxmox API secret without displaying it."""
    secret = os.environ.get("PVE_TOKEN_SECRET", "").strip()
    if secret:
        return secret

    token_file = os.environ.get("PVE_TOKEN_FILE", "").strip()
    if not token_file:
        raise ValueError("Set PVE_TOKEN_SECRET or PVE_TOKEN_FILE")

    content = Path(token_file).read_text(encoding="utf-8")

    # Parse the table generated by `pveum user token add`.
    for line in content.splitlines():
        parts = [part.strip() for part in line.split("│") if part.strip()]

        if len(parts) >= 2 and parts[0] == "value":
            secret = parts[1]
            if secret:
                return secret

    raise ValueError("Could not find the API token secret in the token file")

def list_vms():
    """Return the Proxmox cluster VM inventory without modifying any VM."""
    base_url = os.environ.get("PVE_URL", "").rstrip("/")
    token_id = os.environ.get("PVE_TOKEN_ID", "")

    if not base_url:
        raise ValueError("Set PVE_URL")

    if not token_id:
        raise ValueError("Set PVE_TOKEN_ID")

    token_secret = load_token_secret()
    if not base_url.startswith("https://"):
        raise ValueError("PVE_URL must begin with https://")
    if not os.environ.get("PVE_CA_CERT"):
        raise ValueError("Set PVE_CA_CERT to a trusted CA PEM file; TLS verification is mandatory")

    context = ssl.create_default_context(cafile=os.environ["PVE_CA_CERT"])
    request = Request(
        f"{base_url}/api2/json/cluster/resources?type=vm",
        headers={"Authorization": f"PVEAPIToken={token_id}={token_secret}"},
        method="GET",
    )
    with urlopen(request, context=context, timeout=10) as response:
        payload = json.load(response)
    return normalize_vm_inventory(payload)

def list_snapshots(vmid, node="pve"):
    """List existing Proxmox VM snapshots (read-only)."""
    base_url = os.environ.get("PVE_URL", "").rstrip("/")
    token_id = os.environ.get("PVE_TOKEN_ID", "")

    if not base_url.startswith("https://"):
        raise ValueError("Set a valid HTTPS PVE_URL")
    if not token_id:
        raise ValueError("Set PVE_TOKEN_ID")
    if not isinstance(vmid, int) or isinstance(vmid, bool) or vmid <= 0:
        raise ValueError("VM ID must be a positive integer")
    if node != "pve":
        raise ValueError("Node is not approved")

    token_secret = load_token_secret()

    context = ssl.create_default_context(
        cafile=os.environ["PVE_CA_CERT"]
    )

    url = f"{base_url}/api2/json/nodes/{node}/qemu/{vmid}/snapshot"

    request = Request(
        url,
        headers={
            "Authorization": f"PVEAPIToken={token_id}={token_secret}"
        },
        method="GET"
    )

    with urlopen(request, context=context, timeout=10) as response:
        payload = json.load(response)

    snapshots = payload["data"]

    return [
        {
            "name": snapshot["name"],
            "description": snapshot.get("description", ""),
            "timestamp": snapshot.get("snaptime")
        }
        for snapshot in snapshots
        if snapshot["name"] != "current"
    ]
